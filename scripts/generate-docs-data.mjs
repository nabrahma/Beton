#!/usr/bin/env node
// Generates everything the docs site derives from source, so nothing on the
// site is asserted by hand:
//
//   apps/docs/public/r/*            the registry, served at /r
//   apps/docs/generated/components.ts   component metadata
//   apps/docs/generated/examples/*.ts   example loaders, one module per component
//   apps/docs/generated/examples.json   example titles, descriptions and source
//   apps/docs/generated/props.json      props tables from TypeScript types
//   apps/docs/generated/a11y.json       accessibility test results
//
// --quick reuses an existing test report instead of re-running the suite.
import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docs = join(root, "apps/docs");
const generated = join(docs, "generated");
const reactPkg = join(root, "packages/react");
const reactSrc = join(reactPkg, "src");
const recipesSrc = join(root, "packages/recipes/src");
const quick = process.argv.includes("--quick");
const require = createRequire(join(docs, "package.json"));
const posix = (p) => p.split("\\").join("/");
const write = (file, content) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
};
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

// fs.cpSync crashes natively on Windows when the path contains non-ASCII
// characters (such as "Béton"), so copy with the basic primitives instead.
function copy(from, to) {
  if (statSync(from).isDirectory()) {
    mkdirSync(to, { recursive: true });
    for (const entry of readdirSync(from)) copy(join(from, entry), join(to, entry));
  } else {
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
  }
}

rmSync(generated, { recursive: true, force: true });

// ---------------------------------------------------------------- registry

const registryDir = join(root, "registry");
if (!existsSync(join(registryDir, "registry.json"))) {
  console.error("registry/ is missing. Run `pnpm registry:build` first.");
  process.exit(1);
}
rmSync(join(docs, "public/r"), { recursive: true, force: true });
copy(join(registryDir, "r"), join(docs, "public/r"));
copy(join(registryDir, "registry.json"), join(docs, "public/r/registry.json"));
copy(join(registryDir, "registry.json"), join(docs, "public/registry.json"));

// -------------------------------------------------------------- components

const componentDirs = readdirSync(reactSrc, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(reactSrc, d.name, `${d.name}.meta.ts`)))
  .map((d) => d.name)
  .sort();

write(
  join(generated, "components.ts"),
  [
    "// Generated by scripts/generate-docs-data.mjs. Do not edit.",
    ...componentDirs.map(
      (name, i) =>
        `import { meta as m${i} } from "${posix(relative(generated, join(reactSrc, name, `${name}.meta.ts`)))}";`,
    ),
    "",
    `export const componentMetas = [${componentDirs.map((_, i) => `m${i}`).join(", ")}];`,
    "",
  ].join("\n"),
);

// Export name -> component folder, for rewriting example imports.
const exportToComponent = new Map();
for (const name of componentDirs) {
  for (const file of readdirSync(join(reactSrc, name))) {
    if (!/\.tsx?$/.test(file) || /\.(test|meta)\.tsx?$/.test(file) || file === "index.ts") continue;
    const source = readFileSync(join(reactSrc, name, file), "utf8");
    for (const m of source.matchAll(/export\s+(?:function|const|interface|type)\s+(\w+)/g)) {
      exportToComponent.set(m[1], { dir: name, file: file.replace(/\.tsx?$/, "") });
    }
  }
}
const exportToRecipe = new Map();
for (const m of readFileSync(join(recipesSrc, "index.ts"), "utf8").matchAll(
  /export\s*\{([^}]*)\}\s*from\s*"\.\/([\w-]+)\.ts"/g,
)) {
  for (const raw of m[1].split(",")) {
    const name = raw.trim().replace(/^type\s+/, "");
    if (name) exportToRecipe.set(name, m[2]);
  }
}

/** Rewrites example imports to the paths a user gets after `beton-ui add`. */
function toInstalledSource(source) {
  return source
    .replace(/^\/\*\*[\s\S]*?\*\/\s*/, "")
    .replace(
      /import\s+(type\s+)?\{([^}]*)\}\s+from\s+"(@beton-ui\/react|@beton-ui\/recipes)";/g,
      (full, typeKeyword = "", clause, pkg) => {
        const groups = new Map();
        for (const raw of clause
          .split(",")
          .map((s) => s.trim())
          .filter(Boolean)) {
          const bare = raw.replace(/^type\s+/, "");
          let target;
          if (pkg === "@beton-ui/react") {
            const owner = exportToComponent.get(bare);
            if (!owner) return full;
            target = `@/components/ui/beton/${owner.file}`;
          } else {
            const recipe = exportToRecipe.get(bare);
            if (!recipe) return full;
            target = ["tv", "shared"].includes(recipe)
              ? `@/lib/beton/${recipe}`
              : `@/lib/beton/recipes/${recipe}.recipe`;
          }
          groups.set(target, [...(groups.get(target) ?? []), raw]);
        }
        return [...groups]
          .map(
            ([target, names]) => `import ${typeKeyword}{ ${names.join(", ")} } from "${target}";`,
          )
          .join("\n");
      },
    );
}

// ---------------------------------------------------------------- examples

const examplesRoot = join(docs, "examples");
const examplesIndex = {};
for (const name of componentDirs) {
  const dir = join(examplesRoot, name);
  if (!existsSync(dir)) {
    console.warn(`No examples for ${name}`);
    continue;
  }
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".tsx"))
    .sort();
  const entries = files.map((file) => {
    const source = readFileSync(join(dir, file), "utf8");
    const doc = source.match(/^\/\*\*([\s\S]*?)\*\//);
    const lines = doc
      ? doc[1]
          .split("\n")
          .map((l) => l.replace(/^\s*\*\s?/, "").trim())
          .filter(Boolean)
      : [];
    const id = basename(file, ".tsx");
    return {
      id,
      title: lines[0] ?? id,
      description: lines.slice(1).join(" "),
      source: toInstalledSource(source).trimEnd(),
    };
  });
  examplesIndex[name] = {
    playground: entries.find((e) => e.id === "playground") ?? null,
    examples: entries.filter((e) => e.id !== "playground"),
  };

  write(
    join(generated, "examples", `${name}.ts`),
    [
      "// Generated by scripts/generate-docs-data.mjs. Do not edit.",
      ...files.map(
        (file, i) =>
          `import E${i} from "${posix(relative(join(generated, "examples"), join(dir, file))).replace(/\.tsx$/, "")}";`,
      ),
      "",
      "export const examples = {",
      ...files.map((file, i) => `  ${JSON.stringify(basename(file, ".tsx"))}: E${i},`),
      "};",
      "",
    ].join("\n"),
  );
}
write(join(generated, "examples.json"), json(examplesIndex));
write(
  join(generated, "example-loaders.ts"),
  [
    "// Generated by scripts/generate-docs-data.mjs. Do not edit.",
    "export const exampleLoaders = {",
    ...Object.keys(examplesIndex).map(
      (name) => `  ${JSON.stringify(name)}: () => import("./examples/${name}"),`,
    ),
    "};",
    "",
  ].join("\n"),
);

// ------------------------------------------------------------------- props

const docgen = require("react-docgen-typescript");
const parser = docgen.withCustomConfig(join(reactPkg, "tsconfig.json"), {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: true,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) =>
    !prop.parent || !/node_modules[\\/]@types[\\/]react/.test(prop.parent.fileName),
});

const props = {};
for (const name of componentDirs) {
  const { meta } = await import(pathToFileURL(join(reactSrc, name, `${name}.meta.ts`)).href);
  const files = readdirSync(join(reactSrc, name))
    .filter((f) => f.endsWith(".tsx") && !f.endsWith(".test.tsx"))
    .map((f) => join(reactSrc, name, f));

  for (const doc of parser.parse(files)) {
    if (!meta.exports.includes(doc.displayName)) continue;
    const ordered = Object.entries(doc.props)
      .map(([prop, info]) => ({
        name: prop,
        type:
          info.type.name === "enum" && Array.isArray(info.type.value)
            ? info.type.value.map((v) => v.value).join(" | ")
            : info.type.name,
        default: info.defaultValue?.value ?? null,
        required: info.required,
        description: info.description,
        inherited: Boolean(info.parent && /node_modules/.test(info.parent.fileName)),
      }))
      .sort(
        (a, b) =>
          Number(a.inherited) - Number(b.inherited) || Number(b.required) - Number(a.required),
      );
    props[doc.displayName] = ordered;
  }

  // Compound parts: Object.assign(Root, { Part: Fn }) with renderElement("tag", ...)
  for (const file of files) {
    const source = readFileSync(file, "utf8");
    const assign = source.match(/export const (\w+) = Object\.assign\(\w+, \{([^}]*)\}\)/);
    if (!assign) continue;
    const [, rootName, body] = assign;
    for (const [, part, fn] of body.matchAll(/(\w+):\s*(\w+)/g)) {
      const tag = source.match(
        new RegExp(`function ${fn}\\([\\s\\S]*?renderElement\\(\\s*"(\\w+)"`),
      )?.[1];
      props[`${rootName}.${part}`] = [
        {
          name: "render",
          type: "RenderProp",
          default: null,
          required: false,
          description: `Replace the rendered <${tag ?? "div"}> or compose with another component.`,
          inherited: false,
        },
        {
          name: "...props",
          type: `ComponentProps<"${tag ?? "div"}">`,
          default: null,
          required: false,
          description: `All props of <${tag ?? "div"}>, including className and ref.`,
          inherited: false,
        },
      ];
    }
  }
}
write(join(generated, "props.json"), json(props));

// -------------------------------------------------------------------- a11y

// A dedicated report file, so a parallel `pnpm test` run never writes the same file.
const reportFile = join(reactPkg, "reports/docs-a11y.json");
if (!quick || !existsSync(reportFile)) {
  console.log("Running the component test suite for accessibility results...");
  const run = spawnSync(
    process.execPath,
    [
      join(dirname(require.resolve("vitest/package.json", { paths: [reactPkg] })), "vitest.mjs"),
      "run",
      "--reporter=json",
      `--outputFile=${reportFile}`,
    ],
    { cwd: reactPkg, stdio: ["ignore", "ignore", "inherit"] },
  );
  if (!existsSync(reportFile)) {
    console.error("The test suite did not produce a report.");
    process.exit(1);
  }
  if (run.status !== 0)
    console.warn("Some component tests failed; the results page will show them.");
}

const TAGS = ["axe", "keyboard", "name", "focus", "motion"];
const report = JSON.parse(readFileSync(reportFile, "utf8"));
const a11y = {
  generatedAt: new Date(report.startTime ?? Date.now()).toISOString(),
  components: {},
};
for (const file of report.testResults ?? []) {
  const dir = posix(relative(reactSrc, file.name)).split("/")[0];
  if (!componentDirs.includes(dir)) continue;
  const entry = (a11y.components[dir] ??= { total: 0, passed: 0, tags: {}, tests: [] });
  for (const test of file.assertionResults ?? []) {
    const passed = test.status === "passed";
    entry.total += 1;
    entry.passed += passed ? 1 : 0;
    const tags = TAGS.filter((tag) => test.title.includes(`[${tag}]`));
    for (const tag of tags) {
      const t = (entry.tags[tag] ??= { total: 0, passed: 0 });
      t.total += 1;
      t.passed += passed ? 1 : 0;
    }
    entry.tests.push({ title: test.title.replace(/\[\w+\]\s*/g, ""), tags, passed });
  }
}
write(join(generated, "a11y.json"), json(a11y));

console.log(
  `Docs data: ${componentDirs.length} components, ${Object.values(examplesIndex).reduce(
    (n, e) => n + e.examples.length,
    0,
  )} examples, ${Object.keys(props).length} props tables, accessibility results for ${
    Object.keys(a11y.components).length
  } components.`,
);
